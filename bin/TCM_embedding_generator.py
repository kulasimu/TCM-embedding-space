class TCMEmbeddingGenerator:
    def __init__(self,
                 model_dir='core/trained_model/model_epoch_60.pkl',
                 save_dir='results/embeddings',
                 device='cpu',
                 symptom_list_dir='core/standard_TCM_entities/symptom_list.pkl',
                 symptom_semantic_dir='core/standard_TCM_entities/symptom_semantic_encodings.pkl',
                 herb_list_dir='core/standard_TCM_entities/herb_list.pkl'):
        """
        TCM embedding vector generator
        :param data_type: The type of input data, can be 'Symptoms' or 'Herbs'
        :param data_dir: The input data directory
        :param model_path: The trained embedding model directory
        :param save_dir: Output embedding saving path
        """
        # Initialization
        self.model_dir = model_dir
        self.save_dir = save_dir
        self.device = device
        self.symptom_list_dir = symptom_list_dir
        self.symptom_semantic_dir = symptom_semantic_dir
        self.herb_list_dir = herb_list_dir


        # Hyperparameters for the embeddings space
        self.n_herb_seq = 30  # Max number of input herbs
        self.n_sym_seq = 40  # Max number of input symptoms
        self.MAX_HERB_LEN = self.n_herb_seq + 1
        self.MAX_SYM_LEN = self.n_sym_seq + 1
        self.EMBEDDING_DIM = 256  # The dimension of embedding space

        # Load the trained model and preprocessed data
        self._load_trained_model()
        self._load_standardized_terms()


    def _load_standardized_terms(self):
        """ Load the standardized terms of symptoms and herbs """

        # 加载各种索引数据
        data_files = {
            'herb_list': self.herb_list_dir,
            'symptom_list': self.symptom_list_dir,
            'symptom_semantics': self.symptom_semantic_dir
        }

        for key, path in data_files.items():
            with open(path, 'rb') as fp:
                setattr(self, key, pickle.load(fp))

        # Attach padding, starting and ending tokens to the list
        self.symptom_list_tmp = self.symptom_list + ['<pad>'] + ['<S>'] + ['<E>']
        self.herb_list_tmp = self.herb_list + ['<pad>'] + ['<S>'] + ['<E>']
        self.symptom2id = {
            symptom: idx
            for idx, symptom in enumerate(self.symptom_list)
        }

        self.herb2id = {
            herb: idx
            for idx, herb in enumerate(self.herb_list)
        }

    def _load_trained_model(self):
        """ Load trained model """
        self.model = torch.load(self.model_dir, map_location=self.device, weights_only=False)
        self.model.to(self.device)
        self.model.eval()

    def _generate_herb_data(self, herb_id_seq, inOrOut='input'):
        """ Generate herb input sequence """
        seq = [len(self.herb_list) + 1] + herb_id_seq if inOrOut == 'input' else herb_id_seq + [
            len(self.herb_list) + 2]
        return seq + [len(self.herb_list)] * (self.MAX_HERB_LEN - len(seq))

    def _generate_sym_data_from_ids(self, sym_id_seq, inOrOut='input'):
        """ Generate symptom input sequence (for standardized symptom terms only) """
        seq = [len(self.symptom_list) + 1] + sym_id_seq if inOrOut == 'input' else sym_id_seq + [
            len(self.symptom_list) + 2]
        seq = seq + [len(self.symptom_list)] * (self.MAX_SYM_LEN - len(seq))
        embeddings = [self.symptom_semantics[s] for s in seq]
        return embeddings

    def _generate_sym_data_from_semantics(self, sym_semantic_seq, inOrOut='input'):
        """ Generate symptom input sequence (for all symptoms, directly from semantic vectors), available only if you have generated the sematic vectors using GUSE """
        semantics = [self.symptom_semantics[len(self.symptom_list) + 1]] + sym_semantic_seq if inOrOut == 'input' else sym_semantic_seq + [self.symptom_semantics[len(self.symptom_list) + 2]]
        return semantics + [self.symptom_semantics[len(self.symptom_list)]] * (self.MAX_SYM_LEN - len(semantics))

    def generate_symptom_embedding(self, case_symptoms, input_type='standard_symptoms'):
        '''
        Input type can be standard symptoms (string) or semantic vectors (array generated by GUSE)
        '''
        herb_inputs, symptom_inputs = [], []
        if input_type == 'standard_symptoms':
            for symptoms_seq in case_symptoms:
                sym_id_seq = [self.symptom_list.index(s) for s in symptoms_seq if s in self.symptom_list]

                symptom_inputs.append(self._generate_sym_data_from_ids(sym_id_seq, 'input'))
                herb_inputs.append(self._generate_herb_data([], 'input'))  # empty herb input
        else:
            for symptoms_semantic_seq in case_symptoms:
                symptom_inputs.append(self._generate_sym_data_from_semantics(symptoms_semantic_seq, 'input'))
                herb_inputs.append(self._generate_herb_data([], 'input'))  # empty herb input
        # print(symptom_inputs)

        # Generate embeddings
        herb_tensor = torch.IntTensor(np.array(herb_inputs)).to(self.device)
        sym_tensor = torch.FloatTensor(np.array(symptom_inputs)).to(self.device)
        with torch.no_grad():
            _, _, z1, z2, _ = self.model(sym_tensor, herb_tensor)

        return z1.cpu().numpy().astype(np.float32)

    def generate_herb_embedding(self, case_herbs):
        herb_inputs, symptom_inputs = [], []
        for herb_seq in case_herbs:
            herb_id_seq = [self.herb_list.index(h) for h in herb_seq if h in self.herb_list]
            symptom_inputs.append(self._generate_sym_data_from_ids([], 'input'))  # empty symptom input
            herb_inputs.append(self._generate_herb_data(herb_id_seq, 'input'))

        # Generate embeddings
        herb_tensor = torch.IntTensor(np.array(herb_inputs)).to(self.device)
        sym_tensor = torch.FloatTensor(np.array(symptom_inputs)).to(self.device)
        with torch.no_grad():
            _, _, z1, z2, _ = self.model(sym_tensor, herb_tensor)

        return z2.cpu().numpy().astype(np.float32)


    def extract_cross_attention(
        self,
        case_symptoms,
        case_herbs,
    ):
        """
        Extract last-layer cross-attention maps from matched
        symptom-pattern and formula records.

        Parameters
        ----------
        case_symptoms : list[list[str]]
            Symptom sets for multiple matched records.

        case_herbs : list[list[str]]
            Herb sets for the corresponding formulas.

        Returns
        -------
        records : list[dict]
            One dictionary per matched symptom-formula record.
        """
        if len(case_symptoms) != len(case_herbs):
            raise ValueError(
                "case_symptoms and case_herbs must have the same length."
            )

        symptom_inputs = []
        herb_inputs = []

        valid_symptoms_all = []
        valid_herbs_all = []

        for symptoms, herbs in zip(case_symptoms, case_herbs):

            # Remove duplicated entities while preserving order
            symptoms = list(dict.fromkeys(symptoms))
            herbs = list(dict.fromkeys(herbs))

            valid_symptoms = [
                symptom
                for symptom in symptoms
                if symptom in self.symptom2id
            ][:self.n_sym_seq]

            valid_herbs = [
                herb
                for herb in herbs
                if herb in self.herb2id
            ][:self.n_herb_seq]

            symptom_ids = [
                self.symptom2id[symptom]
                for symptom in valid_symptoms
            ]

            herb_ids = [
                self.herb2id[herb]
                for herb in valid_herbs
            ]

            symptom_inputs.append(
                self._generate_sym_data_from_ids(
                    symptom_ids,
                    inOrOut="input",
                )
            )

            herb_inputs.append(
                self._generate_herb_data(
                    herb_ids,
                    inOrOut="input",
                )
            )

            valid_symptoms_all.append(valid_symptoms)
            valid_herbs_all.append(valid_herbs)

        symptom_tensor = torch.FloatTensor(
            np.asarray(symptom_inputs)
        ).to(self.device)

        herb_tensor = torch.LongTensor(
            np.asarray(herb_inputs)
        ).to(self.device)

        with torch.no_grad():
            _, _, z_sym, z_herb, attention_list = self.model(
                symptom_tensor,
                herb_tensor,
                mask_input=None,
            )

        # attention_list = [w1, w2, w12, w21]
        w12_layers = attention_list[2]
        w21_layers = attention_list[3]

        # Only save the last cross-attention layer
        w12_last = w12_layers[-1]
        w21_last = w21_layers[-1]

        # Current model normally returns:
        # [batch, query_length, key_length]
        #
        # If average_attn_weights=False is later enabled:
        # [batch, heads, query_length, key_length]
        if w12_last.dim() == 4:
            w12_last = w12_last.mean(dim=1)

        if w21_last.dim() == 4:
            w21_last = w21_last.mean(dim=1)

        output_records = []

        for sample_idx, (symptoms, herbs) in enumerate(
            zip(valid_symptoms_all, valid_herbs_all)
        ):
            n_symptoms = len(symptoms)
            n_herbs = len(herbs)

            # Token sequence:
            # position 0 = <S>
            # positions 1:n+1 = real tokens
            #
            # w12:
            # symptom query × herb key
            symptom_to_herb_attention = (
                w12_last[
                    sample_idx,
                    1:n_symptoms + 1,
                    1:n_herbs + 1,
                ]
                .cpu()
                .numpy()
                .astype(np.float32)
            )

            # w21:
            # herb query × symptom key
            herb_to_symptom_attention = (
                w21_last[
                    sample_idx,
                    1:n_herbs + 1,
                    1:n_symptoms + 1,
                ]
                .cpu()
                .numpy()
                .astype(np.float32)
            )

            # Average over query tokens to obtain key-token importance
            #
            # Each herb's average attention received from symptom queries
            herb_importance = symptom_to_herb_attention.mean(axis=0)

            # Each symptom's average attention received from herb queries
            symptom_importance = herb_to_symptom_attention.mean(axis=0)

            # Normalize to sum to 1
            if herb_importance.sum() > 0:
                herb_importance = (
                    herb_importance / herb_importance.sum()
                )

            if symptom_importance.sum() > 0:
                symptom_importance = (
                    symptom_importance / symptom_importance.sum()
                )

            output_records.append({
                "symptoms": symptoms,
                "herbs": herbs,

                # shape: [n_symptoms, n_herbs]
                "symptom_to_herb_cross_attention":
                    symptom_to_herb_attention,

                # shape: [n_herbs, n_symptoms]
                "herb_to_symptom_cross_attention":
                    herb_to_symptom_attention,

                # shape: [n_symptoms]
                "symptom_importance":
                    symptom_importance.astype(np.float32),

                # shape: [n_herbs]
                "herb_importance":
                    herb_importance.astype(np.float32),

                # Optional: matched set embeddings
                "symptom_set_embedding":
                    z_sym[sample_idx]
                    .cpu()
                    .numpy()
                    .astype(np.float32),

                "formula_set_embedding":
                    z_herb[sample_idx]
                    .cpu()
                    .numpy()
                    .astype(np.float32),
            })

        return output_records


    def save_embeddings(self, embeddings_dict={}):
        """ Save the embeddings """
        for key, value in embeddings_dict.items():
            with open(f'{self.save_dir}/{key}.pkl', 'wb') as fp:
                pickle.dump(value, fp)

    def herb_decoding(self, symptoms, input_type='standard_symptoms', printout=True):
        '''
        Decode herbal therapy from symptom embeddings (for one case)
        :param symptoms: Input symptoms
        :param input_type: Whether the input symptom are standardized terms
        :param printout: print
        :return:
        '''

        if printout:
            print('Symptoms: ', " ".join(symptoms))

        if input_type == 'standard_symptoms':
            sym_id_seq = [self.symptom_list.index(s) for s in symptoms]
            symptom_input = self._generate_sym_data_from_ids(sym_id_seq, 'input')
        else:
            symptom_input = self._generate_sym_data_from_semantics(symptoms, 'input')
        symptom_input = torch.FloatTensor(np.array([symptom_input])).to(self.device)

        num_herbs = len(self.herb_list)
        herb_input_list = [int(num_herbs + 1)]  # Start with '<S>'
        for seq in range(1, self.MAX_HERB_LEN + 1):
            herb_input = torch.IntTensor([herb_input_list]).to(self.device)
            _, pred_seq, _, _, _ = self.model(symptom_input, herb_input)
            pred_seq = torch.squeeze(pred_seq, dim=0).cpu().detach().numpy()
            pred_rank = np.argsort(-pred_seq[-1])
            for p in pred_rank:
                if p not in herb_input_list:
                    herb_input_list.append(int(p))
                    break
            if printout:
                print('Input:', ";".join([self.herb_list_tmp[h] for h in herb_input_list[:-1]]), '    Output:',self.herb_list_tmp[herb_input_list[-1]])
            if herb_input_list[-1] == num_herbs + 2:
                break
        return [self.herb_list[h] for h in herb_input_list[1:-1]]


    def symptom_decoding(self, herbs, printout=True):
        '''
        Decode symptoms from herb embeddings (for one case)
        :param symptoms:
        :param standard_symptoms:
        :param printout:
        :return:
        '''

        if printout:
            print('Herbs: ', " ".join(herbs))

        herb_id_seq = [self.herb_list.index(h) for h in herbs]
        herb_input = torch.IntTensor([self._generate_herb_data(herb_id_seq, 'input')]).to(self.device)

        num_symptoms = len(self.symptom_list)
        symptom_input_id_list = [int(num_symptoms + 1)]  # Start with '<S>'
        for seq in range(1, self.MAX_SYM_LEN + 1):
            sym_input = torch.FloatTensor(np.array([[self.symptom_semantics[s] for s in symptom_input_id_list]])).to(self.device)
            pred_seq, _, _, _, _ = self.model(sym_input, herb_input, mask_input='symptom')
            pred_seq = torch.squeeze(pred_seq, dim=0).cpu().detach().numpy()
            pred_rank = np.argsort(-pred_seq[-1])
            for p in pred_rank:
                if p not in symptom_input_id_list:
                    symptom_input_id_list.append(p)
                    break
            if printout:
                print('Input:', ";".join([self.symptom_list_tmp[s] for s in symptom_input_id_list[:-1]]), '    Output:',self.symptom_list_tmp[symptom_input_id_list[-1]])
            if symptom_input_id_list[-1] == num_symptoms + 2:
                break

        return [self.symptom_list[s] for s in symptom_input_id_list[1:-1]]


def get_non_zero_symptoms(row, initialOrFollowup):
    # For each patient (row), find out symptoms (column) with non-zero scores in initial or follow-up visit
    # initialOrFollowup: suffix of the column name, can be "initial" or "followup"
    symptoms = [col.split("-")[0] for col in row.index if col.endswith(initialOrFollowup) and row[col] != 0]
    return symptoms

def get_semantics(symptoms, sym_list, sym_semantics):
    return [sym_semantics[sym_list.index(s)] for s in symptoms]


def unique_list(x):
    """
    Remove duplicated terms while preserving the original order.
    """
    out = []
    seen = set()

    for item in x:
        if item not in seen:
            out.append(item)
            seen.add(item)

    return out






def generate_formula_record_embeddings(
        generator,
        formula_records_data_pd,
        out_dir="results/embeddings/TCM_embeddings",
        batch_size=1000,
):
    """Generate symptom-pattern and formula embeddings for eligible formula records."""
    n_herb_seq = generator.n_herb_seq
    n_sym_seq = generator.n_sym_seq

    selected_formula_ids = []
    for i in range(len(formula_records_data_pd)):
        n_h = len(formula_records_data_pd.iloc[i]['Herbs'])
        n_s = len(formula_records_data_pd.iloc[i]['Symptoms'])
        if n_s <= n_sym_seq and n_h <= n_herb_seq and n_s >= 1 and n_h >= 1:
            selected_formula_ids.append(i)

    print('Number of selected formula records: ', len(selected_formula_ids))

    selected_symptom_inputs = formula_records_data_pd.iloc[selected_formula_ids]["Symptoms"].tolist()
    selected_herb_inputs = formula_records_data_pd.iloc[selected_formula_ids]["Herbs"].tolist()

    selected_herb_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )
    selected_symptom_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )

    for start in range(0, len(selected_formula_ids), batch_size):
        end = min(start + batch_size, len(selected_formula_ids))
        print(f"Generating formula-record embeddings: {start} - {end}", flush=True)

        herb_embedding = generator.generate_herb_embedding(
            selected_herb_inputs[start:end]
        )
        symptom_embedding = generator.generate_symptom_embedding(
            selected_symptom_inputs[start:end]
        )

        selected_herb_embeddings = np.concatenate(
            (selected_herb_embeddings, herb_embedding), axis=0
        )
        selected_symptom_embeddings = np.concatenate(
            (selected_symptom_embeddings, symptom_embedding), axis=0
        )

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "selected_formula_herb_embeddings.pkl"), 'wb') as fp:
        pickle.dump(selected_herb_embeddings, fp)
    with open(os.path.join(out_dir, "selected_formula_symptom_embeddings.pkl"), 'wb') as fp:
        pickle.dump(selected_symptom_embeddings, fp)
    with open(os.path.join(out_dir, "selected_formula_ids(line_number).pkl"), 'wb') as fp:
        pickle.dump(selected_formula_ids, fp)


def generate_individual_embeddings(
        generator,
        herb_list,
        symptom_list,
        out_dir="results/embeddings/TCM_embeddings",
):
    """Generate TCM-ES embeddings for individual standardized herbs and symptoms."""
    herb_embeddings = generator.generate_herb_embedding([[h] for h in herb_list])
    symptom_embeddings = generator.generate_symptom_embedding([[s] for s in symptom_list])

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "individual_herb_embeddings.pkl"), 'wb') as fp:
        pickle.dump(herb_embeddings, fp)
    with open(os.path.join(out_dir, "individual_symptom_embeddings.pkl"), 'wb') as fp:
        pickle.dump(symptom_embeddings, fp)


def filter_general_cases_by_herb_vocabulary(general_cases_df, herb_list):
    """Retain cases whose prescribed formula contains only standardized model herbs."""
    herb_set = set(herb_list)
    valid_formula_mask = general_cases_df["Formula"].apply(
        lambda herbs: (
            isinstance(herbs, (list, tuple))
            and len(herbs) > 0
            and all(h in herb_set for h in herbs)
        )
    )
    return general_cases_df.loc[valid_formula_mask].reset_index(drop=True)


def generate_general_case_embeddings(
        generator,
        clinical_data_path,
        out_dir="results/embeddings/general_TCM_clinical_cases/original",
        batch_size=1000,
):
    """Generate TCM-ES embeddings for general TCM clinical cases."""
    general_cases_df = pd.read_pickle(clinical_data_path)
    general_cases_df = filter_general_cases_by_herb_vocabulary(
        general_cases_df, generator.herb_list
    )

    filtered_data_path = os.path.splitext(clinical_data_path)[0] + "_model_eligible.pkl"
    general_cases_df.to_pickle(filtered_data_path)
    print(general_cases_df)
    print(
        "General TCM clinical cases after herb-vocabulary filtering:",
        len(general_cases_df),
    )
    print("Filtered clinical-case dataframe saved to:", filtered_data_path)

    case_ids = list(general_cases_df["Cases_id"])
    case_symptom_inputs = list(general_cases_df["Initial_symptoms"])
    case_herb_inputs = list(general_cases_df["Formula"])
    case_alleviated_symptoms = list(general_cases_df["Alleviated_symptoms"])

    print("Number of selected general TCM clinical cases:", len(case_ids))

    case_improved_symptom_inputs = []
    case_unimproved_symptom_inputs = []

    for initial_symptoms, alleviated_symptoms in zip(
            case_symptom_inputs, case_alleviated_symptoms
    ):
        initial_symptoms = unique_list(initial_symptoms)
        alleviated_set = set(alleviated_symptoms)
        improved_symptoms = [s for s in initial_symptoms if s in alleviated_set]
        unimproved_symptoms = [s for s in initial_symptoms if s not in alleviated_set]
        case_improved_symptom_inputs.append(improved_symptoms)
        case_unimproved_symptom_inputs.append(unimproved_symptoms)

    case_symptom_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )
    case_herb_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )
    case_improved_symptom_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )
    case_unimproved_symptom_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )

    for start in range(0, len(case_ids), batch_size):
        end = min(start + batch_size, len(case_ids))
        print(f"Generating general clinical-case embeddings: {start} - {end}", flush=True)

        symptom_embedding = generator.generate_symptom_embedding(
            case_symptom_inputs[start:end]
        )
        herb_embedding = generator.generate_herb_embedding(
            case_herb_inputs[start:end]
        )
        improved_embedding = generator.generate_symptom_embedding(
            case_improved_symptom_inputs[start:end]
        )
        unimproved_embedding = generator.generate_symptom_embedding(
            case_unimproved_symptom_inputs[start:end]
        )

        case_symptom_embeddings = np.concatenate(
            (case_symptom_embeddings, symptom_embedding), axis=0
        )
        case_herb_embeddings = np.concatenate(
            (case_herb_embeddings, herb_embedding), axis=0
        )
        case_improved_symptom_embeddings = np.concatenate(
            (case_improved_symptom_embeddings, improved_embedding), axis=0
        )
        case_unimproved_symptom_embeddings = np.concatenate(
            (case_unimproved_symptom_embeddings, unimproved_embedding), axis=0
        )

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "case_symptom_embeddings.pkl"), "wb") as fp:
        pickle.dump(case_symptom_embeddings, fp)
    with open(os.path.join(out_dir, "case_herb_embeddings.pkl"), "wb") as fp:
        pickle.dump(case_herb_embeddings, fp)
    with open(os.path.join(out_dir, "case_improved_symptom_embeddings.pkl"), "wb") as fp:
        pickle.dump(case_improved_symptom_embeddings, fp)
    with open(os.path.join(out_dir, "case_unimproved_symptom_embeddings.pkl"), "wb") as fp:
        pickle.dump(case_unimproved_symptom_embeddings, fp)
