def generate_covid_embeddings(
        generator,
        covid_data_path="data/COVID_19/example_COVID_19_data.pkl",
        formula_composition_path="data/COVID_19/COVID_19_formula_composition.pkl",
        symptom_list_path="data/COVID_19/COVID_19_symptom_list.pkl",
        symptom_semantic_path="data/COVID_19/COVID_19_symptom_semantics.pkl",
        out_dir="results/embeddings/COVID_19",
):
    """Generate patient-condition and prescribed-formula embeddings for the COVID-19 example data."""
    example_covid_19_data_pd = pd.read_pickle(covid_data_path)

    with open(formula_composition_path, 'rb') as fp:
        covid_formula_composition = pickle.load(fp)
    with open(symptom_list_path, 'rb') as fp:
        covid_symptoms = pickle.load(fp)
    with open(symptom_semantic_path, 'rb') as fp:
        covid_symptom_semantics = pickle.load(fp)[:60]

    initial_symptoms = list(
        example_covid_19_data_pd.apply(
            get_non_zero_symptoms, axis=1, initialOrFollowup='initial'
        )
    )
    initial_symptom_semantics = [
        get_semantics(s, covid_symptoms, covid_symptom_semantics)
        for s in initial_symptoms
    ]
    initial_symptom_embeddings = generator.generate_symptom_embedding(
        initial_symptom_semantics, input_type='semantic'
    )

    covid_formula_embeddings = {}
    for formula_name in ['方1', '方3', '方4', '方6', '方A', '方B', '方C1', '方C2', '方D']:
        if formula_name in covid_formula_composition:
            covid_formula_embeddings[formula_name] = generator.generate_herb_embedding(
                [covid_formula_composition[formula_name]]
            )[0]

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "COVID_19_initial_symptom_embeddings.pkl"), 'wb') as fp:
        pickle.dump(initial_symptom_embeddings, fp)
    with open(os.path.join(out_dir, "COVID_19_formula_embeddings.pkl"), 'wb') as fp:
        pickle.dump(covid_formula_embeddings, fp)


def generate_external_all_valid_embeddings(
        generator,
        external_formula_data_path="data/TCM_PD_external/TCM_PD_formula_data_external_all_valid.pkl",
        out_dir="results/embeddings/TCM_PD_external/original",
        batch_size=1000,
):
    """Generate row-aligned embeddings for all valid external TCM-PD formula records."""
    external_all_valid_pd = pd.read_pickle(external_formula_data_path).reset_index(drop=True)
    external_symptom_inputs = external_all_valid_pd["Symptoms"].tolist()
    external_herb_inputs = external_all_valid_pd["Herbs"].tolist()

    symptom_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )
    herb_embeddings = np.zeros(
        (0, generator.EMBEDDING_DIM), dtype=np.float32
    )

    for start in range(0, len(external_all_valid_pd), batch_size):
        end = min(start + batch_size, len(external_all_valid_pd))
        print(f"Generating external TCM-PD embeddings: {start} - {end}", flush=True)

        symptom_embedding = generator.generate_symptom_embedding(
            external_symptom_inputs[start:end]
        )
        herb_embedding = generator.generate_herb_embedding(
            external_herb_inputs[start:end]
        )

        symptom_embeddings = np.concatenate(
            (symptom_embeddings, symptom_embedding), axis=0
        )
        herb_embeddings = np.concatenate(
            (herb_embeddings, herb_embedding), axis=0
        )

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "external_all_valid_symptom_embeddings.pkl"), "wb") as fp:
        pickle.dump(symptom_embeddings, fp)
    with open(os.path.join(out_dir, "external_all_valid_herb_embeddings.pkl"), "wb") as fp:
        pickle.dump(herb_embeddings, fp)



def generate_test_cross_attention(
        generator,
        formula_records_data_pd,
        test_idx_path="data/training/test_idx.pkl",
        out_dir="results/attention/original/test",
        batch_size=1000,
):
    """Extract and save cross-attention records for the held-out test split."""
    if batch_size < 1:
        raise ValueError("batch_size must be a positive integer.")

    with open(test_idx_path, "rb") as fp:
        test_idx = [int(x) for x in pickle.load(fp)]

    n_rows = len(formula_records_data_pd)
    invalid_ids = [idx for idx in test_idx if idx < 0 or idx >= n_rows]
    if invalid_ids:
        raise IndexError(
            "test_idx contains indices outside formula-data row range: "
            f"{invalid_ids[:20]}"
        )

    required_columns = {"Symptoms", "Herbs"}
    missing_columns = required_columns.difference(formula_records_data_pd.columns)
    if missing_columns:
        raise KeyError(
            "Formula data is missing required columns: "
            + ", ".join(sorted(missing_columns))
        )

    attention_record_ids = []
    for record_id in test_idx:
        row = formula_records_data_pd.iloc[record_id]
        n_symptoms = len(row["Symptoms"])
        n_herbs = len(row["Herbs"])
        if (
            1 <= n_symptoms <= generator.n_sym_seq
            and 1 <= n_herbs <= generator.n_herb_seq
        ):
            attention_record_ids.append(record_id)

    print(
        "Number of test records for attention extraction:",
        len(attention_record_ids),
    )

    all_attention_records = []
    for start in range(0, len(attention_record_ids), batch_size):
        end = min(start + batch_size, len(attention_record_ids))
        batch_record_ids = attention_record_ids[start:end]
        batch_df = formula_records_data_pd.iloc[batch_record_ids]

        print(
            f"Extracting cross attention: {start}-{end}/{len(attention_record_ids)}",
            flush=True,
        )

        batch_attention = generator.extract_cross_attention(
            case_symptoms=batch_df["Symptoms"].tolist(),
            case_herbs=batch_df["Herbs"].tolist(),
        )
        if len(batch_attention) != len(batch_record_ids):
            raise RuntimeError(
                "Cross-attention output count does not match the input record count."
            )

        for record_id, result in zip(batch_record_ids, batch_attention):
            result["formula_row_id"] = int(record_id)
            if "ID" in formula_records_data_pd.columns:
                result["formula_record_id"] = formula_records_data_pd.iloc[record_id]["ID"]
            if "Title" in formula_records_data_pd.columns:
                result["formula_title"] = formula_records_data_pd.iloc[record_id]["Title"]

        all_attention_records.extend(batch_attention)

    output_dir = Path(out_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "cross_attention_test_all.pkl"

    attention_output = {
        "split": "test",
        "model_path": generator.model_dir,
        "n_records": len(all_attention_records),
        "record_ids": attention_record_ids,
        "attention_description": {
            "layer": "last cross-attention layer",
            "heads": "head-averaged",
            "input": "matched complete symptom and formula sets",
            "w12": "symptom queries to herb keys",
            "w21": "herb queries to symptom keys",
        },
        "records": all_attention_records,
    }

    with open(output_path, "wb") as fp:
        pickle.dump(attention_output, fp, protocol=pickle.HIGHEST_PROTOCOL)

    print("Cross-attention extraction completed.")
    print("Number of saved records:", len(all_attention_records))
    print("Saved to:", output_path)
    return output_path

def build_parser():
    parser = argparse.ArgumentParser(
        description="Generate TCM-ES embeddings for the public demonstration datasets."
    )
    parser.add_argument(
        "--model-dir",
        default="core/trained_model/model_epoch_60.pkl",
        help="Path to the trained TCM-ES model.",
    )
    parser.add_argument(
        "--formula-data",
        default="data/TCM_formulas/TCM_formula_data_example_2000.pkl",
        help="Formula-record dataframe used for the demonstration.",
    )
    parser.add_argument(
        "--general-clinical-data",
        default="data/general_TCM_clinical_cases/TCM_general_cases_data_example_500.pkl",
        help="Example general TCM clinical-case dataframe.",
    )
    parser.add_argument(
        "--external-pd-data",
        default="data/TCM_PD_external/TCM_PD_formula_data_external_all_valid.pkl",
        help="Prepared external TCM-PD dataframe.",
    )
    parser.add_argument(
        "--tasks",
        nargs="+",
        choices=["formula", "individual", "attention", "general-clinical", "covid", "external-tcm-pd"],
        default=["formula", "individual"],
        help="Embedding modules to run.",
    )

    parser.add_argument(
        "--TCM-out-dir",
        default="results/embeddings/TCM_embeddings",
        help="Output directory for formula-record embeddings.",
    )
    parser.add_argument(
        "--test-idx",
        default="data/training/test_idx.pkl",
        help="Held-out test-set row indices for attention extraction.",
    )
    parser.add_argument(
        "--attention-out-dir",
        default="results/attention/original/test",
        help="Output directory for held-out test-set cross-attention records.",
    )

    parser.add_argument("--batch-size", type=int, default=1000)
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    generator = TCMEmbeddingGenerator(
        model_dir=args.model_dir,
        device=device,
    )

    with open('core/standard_TCM_entities/herb_list.pkl', 'rb') as fp:
        herb_list = pickle.load(fp)
    with open('core/standard_TCM_entities/symptom_list.pkl', 'rb') as fp:
        symptom_list = pickle.load(fp)

    if "formula" in args.tasks:
        formula_records_data_pd = pd.read_pickle(args.formula_data)
        generate_formula_record_embeddings(
            generator,
            formula_records_data_pd,
            out_dir=args.TCM_out_dir,
            batch_size=args.batch_size,
        )

    if "individual" in args.tasks:
        generate_individual_embeddings(
            generator,
            herb_list,
            symptom_list,
            out_dir=args.TCM_out_dir,
        )

    if "attention" in args.tasks:
        formula_records_data_pd = pd.read_pickle(args.formula_data)
        generate_test_cross_attention(
            generator=generator,
            formula_records_data_pd=formula_records_data_pd,
            test_idx_path=args.test_idx,
            out_dir=args.attention_out_dir,
            batch_size=args.batch_size,
        )

    if "general-clinical" in args.tasks:
        generate_general_case_embeddings(
            generator,
            clinical_data_path=args.general_clinical_data,
            out_dir="results/embeddings/general_TCM_clinical_cases/original",
            batch_size=args.batch_size,
        )

    if "covid" in args.tasks:
        generate_covid_embeddings(
            generator,
            out_dir="results/embeddings/COVID_19",
        )

    if "external-tcm-pd" in args.tasks:
        generate_external_all_valid_embeddings(
            generator,
            external_formula_data_path=args.external_pd_data,
            out_dir="results/embeddings/TCM_PD_external/original",
            batch_size=args.batch_size,
        )


if __name__ == "__main__":
    main()
